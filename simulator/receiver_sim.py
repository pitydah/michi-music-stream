    log.info("    PATCH  /api/v1/receiver-lite/session   [auth + session]")
    log.info("    DELETE /api/v1/receiver-lite/session   [auth + session]")
    log.info("    POST   /api/v1/receiver-lite/heartbeat [auth + session]")
