_B64URL_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"


def decode_base64url_strict(value):
    if not isinstance(value, str) or not value or value.endswith("="):
        raise ValueError("invalid base64url (padding not allowed)")
    if any(ch not in _B64URL_ALPHABET for ch in value):
        raise ValueError("invalid base64url character")
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def derive_michi_id(public_key_bytes):
    return base64.urlsafe_b64encode(blake3.blake3(public_key_bytes).digest()).decode("ascii").rstrip("=")

