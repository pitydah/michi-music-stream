def preinit_session(state):
    state.open_pairing_window()
    _, started = state.pairing_start(CONTROLLER_IDENTITY)
    session_id = started["session_id"]
    pin = state.pairing_sessions[session_id]["pin"]
    _, confirmed = state.pairing_confirm(
        session_id, pin, CONTROLLER_IDENTITY["michi_id"], CONTROLLER_IDENTITY["public_key"]
    )
    pairing_token = confirmed["token"]
    _, created = state.session_create(
        {
            "transport": "rtp_udp",
            "codec": "pcm_s16le",
            "sample_rate": 48000,
            "bit_depth": 16,
            "channels": 2,
            "packet_ms": 10,
            "buffer_ms": 250,
            "payload_type": 97,
            "ssrc": 305419896,
            "volume": 70,
        },
        source_ip="127.0.0.1",
    )
    return pairing_token, created["session_token"], created["session_id"]


