#!/usr/bin/env python3
"""Deterministically rasterize the OFFICIAL Michi Stream SVG at build time.

Never renders SVG on the ESP32. Assets are RGB565 flash tables composited
against the exact panel background. Re-run when the official logo changes:
  python3 tools/gen_michi_brand.py
Dependency (developer-only): cairosvg, Pillow.
"""
from io import BytesIO
from pathlib import Path
import hashlib
import cairosvg
from PIL import Image

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / 'assets/brand/michi_stream_official.svg'
DEST = HERE.parent / 'assets/icons/michi_stream_brand_data.h'
BG = (8, 10, 15)  # MICHI_UI_BG / #080A0F
SIZES = (40, 72)


def main():
    svg = SOURCE.read_bytes()
    lines = ["/* Generated by tools/gen_michi_brand.py. DO NOT EDIT.\n",
             " * Official Michi Music Stream logo, RGB565 precomposited to MICHI_UI_BG.\n",
             f" * SVG source SHA-256: {hashlib.sha256(svg).hexdigest()}\n",
             " * 40px / 72px; 2 bytes per pixel in flash, zero heap, band-clipped draw.\n */\n",
             "#pragma once\n#include <stdint.h>\n"]
    for size in SIZES:
        # SVG is rendered at exact target pixel dimensions (no upscaling on ESP32).
        raw = cairosvg.svg2png(bytestring=svg, output_width=size, output_height=size)
        rgba = Image.open(BytesIO(raw)).convert('RGBA')
        under = Image.new('RGBA', (size, size), (*BG, 255))
        under.alpha_composite(rgba)
        rgb = under.convert('RGB')
        data=[]
        for r,g,b in rgb.getdata():
            val = (((r * 31 + 127)//255)<<11) | (((g * 63 + 127)//255)<<5) | ((b*31+127)//255)
            data.append(f'0x{val:04x}u')
        lines.append(f'\nstatic const uint16_t michi_brand_{size}[{size}u * {size}u] = {{\n')
        for i in range(0, len(data), 12):
            lines.append('    ' + ', '.join(data[i:i+12]) + ',\n')
        lines.append('};\n')
    DEST.write_text(''.join(lines), encoding='utf-8')
    print('generated', DEST, DEST.stat().st_size)

if __name__ == '__main__':
    main()
